// Runs this extension's *.webgl.test.ts specs through a Safelight checkout's
// WebGL test harness: headless Chromium on SwiftShader and the real renderer.
// The specs are copied into the checkout for the run (its harness helpers only
// resolve from inside) and removed afterwards, along with the generated config.
// Point SAFELIGHT_CORE at the checkout; by default `SafeLight` beside this
// repository's parent folder is tried, then beside the repository.
// SAFELIGHT_TEST_CHROME names the browser executable to use when Playwright's
// bundled Chromium will not start. The browser server takes a port the OS hands
// out rather than vitest's fixed default, which Windows' dynamic port
// exclusions can swallow.
"use strict";

const fs = require("fs");
const net = require("net");
const path = require("path");
const { spawnSync } = require("child_process");

const extension = path.resolve(__dirname, "..", "..");
const slug = path
  .basename(extension)
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, "-")
  .replace(/^-|-$/g, "");
const isCheckout = (dir) => fs.existsSync(path.join(dir, "vitest.webgl.config.ts"));
const candidates = process.env.SAFELIGHT_CORE
  ? [path.resolve(process.env.SAFELIGHT_CORE)]
  : [path.join(extension, "..", "..", "SafeLight"), path.join(extension, "..", "SafeLight")];
const core = candidates.find(isCheckout);
if (!core) {
  console.error(`No Safelight checkout found (tried ${candidates.join(", ")}); set SAFELIGHT_CORE`);
  process.exit(2);
}

const specDir = path.join(core, "src", "rendering", "webgl", `__${slug}_gpu__`);
const configFile = path.join(core, `vitest.${slug}-gpu.config.ts`);
const executablePath = process.env.SAFELIGHT_TEST_CHROME;
const own = (name) => name !== path.basename(__filename);

const config = (port) => `/// <reference types="vitest/config" />
// Generated by ${path.basename(extension)}'s test/gpu/run.cjs and removed after
// the run. Same rig as vitest.webgl.config.ts, plus the extension's sources.
import path from "path";
import { readFileSync } from "fs";
import { defineConfig } from "vite";
import { playwright } from "@vitest/browser-playwright";

const pkg = JSON.parse(readFileSync(path.resolve(__dirname, "package.json"), "utf-8")) as { version: string };
const EXT = ${JSON.stringify(extension)};

export default defineConfig({
  cacheDir: "node_modules/.vite-cache-${slug}-gpu",
  define: { __APP_VERSION__: JSON.stringify(pkg.version) },
  resolve: {
    alias: {
      "@": path.resolve(__dirname, "src"),
      "libraw-wasm": path.resolve(__dirname, "src/raw/vendor/libraw-wasm/index.js"),
      "@ext": path.join(EXT, "src"),
    },
  },
  server: { fs: { allow: [__dirname, EXT] } },
  optimizeDeps: { exclude: ["libraw-wasm"] },
  test: {
    name: "${slug}-gpu",
    include: ["src/rendering/webgl/__${slug}_gpu__/*.webgl.test.ts"],
    testTimeout: 300_000,
    fileParallelism: false,
    browser: {
      enabled: true,
      headless: true,
      // vitest 4.1 reads Chromium's launch options from the provider only.
      provider: playwright({
        launchOptions: {
          ${executablePath ? `executablePath: ${JSON.stringify(executablePath)},` : ""}
          args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"],
        },
      }),
      api: { port: ${port}, strictPort: true },
      instances: [{ browser: "chromium" }],
    },
  },
});
`;

function freePort() {
  return new Promise((resolve, reject) => {
    const server = net.createServer();
    server.unref();
    server.on("error", reject);
    server.listen(0, "127.0.0.1", () => {
      const { port } = server.address();
      server.close(() => resolve(port));
    });
  });
}

async function main() {
  const port = await freePort();
  let status = 1;
  try {
    fs.mkdirSync(specDir, { recursive: true });
    for (const name of fs.readdirSync(__dirname).filter(own)) {
      fs.copyFileSync(path.join(__dirname, name), path.join(specDir, name));
    }
    fs.writeFileSync(configFile, config(port));
    const result = spawnSync(
      "npx",
      ["vitest", "run", "--config", path.basename(configFile), "--reporter=verbose"],
      { cwd: core, stdio: "inherit", shell: true },
    );
    status = result.status ?? 1;
  } finally {
    fs.rmSync(specDir, { recursive: true, force: true });
    fs.rmSync(configFile, { force: true });
  }
  process.exit(status);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
